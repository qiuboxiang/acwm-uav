"""Deterministic human-readable registry documentation."""

from __future__ import annotations

from pathlib import Path

from researchctl.io import atomic_write_text
from researchctl.schema import CheckpointRecord, DatasetRecord, EvaluationRecord, RunRecord
from researchctl.storage import Registry

HEADER = "<!-- Generated by researchctl data docs. Do not edit manually. -->\n"


def _cell(value: object) -> str:
    if value is None:
        return "—"
    if isinstance(value, list):
        return "<br>".join(str(item) for item in value) or "—"
    if isinstance(value, dict):
        return "<br>".join(f"{key}={item}" for key, item in value.items()) or "—"
    return str(value).replace("|", "\\|").replace("\n", " ")


def _table(headers: list[str], rows: list[list[object]]) -> str:
    if not rows:
        return "_尚无记录。_\n"
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    lines.extend("| " + " | ".join(_cell(value) for value in row) + " |" for row in rows)
    return "\n".join(lines) + "\n"


def render_registry_docs(registry: Registry) -> str:
    datasets = [item for item in registry.list("datasets") if isinstance(item, DatasetRecord)]
    runs = [item for item in registry.list("runs") if isinstance(item, RunRecord)]
    checkpoints = [
        item for item in registry.list("checkpoints") if isinstance(item, CheckpointRecord)
    ]
    evaluations = [
        item for item in registry.list("evaluations") if isinstance(item, EvaluationRecord)
    ]
    parts = [HEADER, "\n# 注册表索引\n"]
    parts.extend(
        [
            "\n## 数据集\n\n",
            _table(
                ["ID", "来源", "许可", "可再分发", "Splits", "DVC", "HF"],
                [
                    [
                        item.id,
                        item.source,
                        item.license,
                        item.redistributable,
                        item.splits,
                        item.dvc_path,
                        item.hf_revision,
                    ]
                    for item in datasets
                ],
            ),
            "\n## 实验\n\n",
            _table(
                ["ID", "状态", "代码", "Dirty", "数据", "指标", "MLflow"],
                [
                    [
                        item.id,
                        item.status,
                        item.code_commit,
                        item.dirty,
                        item.dataset_ids,
                        item.metrics,
                        item.mlflow_run_id,
                    ]
                    for item in runs
                ],
            ),
            "\n## Checkpoint\n\n",
            _table(
                ["ID", "Run", "别名", "SHA256", "选择指标", "DVC", "HF"],
                [
                    [
                        item.id,
                        item.run_id,
                        item.alias,
                        item.sha256,
                        (
                            f"{item.selection_metric}={item.selection_value}"
                            if item.selection_metric
                            else None
                        ),
                        item.dvc_path,
                        item.hf_revision,
                    ]
                    for item in checkpoints
                ],
            ),
            "\n## 评测\n\n",
            _table(
                ["ID", "Checkpoint", "数据", "Suite", "指标"],
                [
                    [item.id, item.checkpoint_id, item.dataset_id, item.suite, item.metrics]
                    for item in evaluations
                ],
            ),
        ]
    )
    return "".join(parts)


def write_registry_docs(root: Path, registry: Registry) -> Path:
    path = root / "docs/generated/README.md"
    atomic_write_text(path, render_registry_docs(registry))
    return path
