import base64, glob, json, os, re
from html import escape
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.abspath(f"{HERE}/../../..")
RES = f"{HERE}/../exploration_v5"; AN = f"{RES}/analysis"; FIG = f"{ROOT}/docs/exploration/v5"; OUT = f"{ROOT}/docs/exploration/v5_report.html"
TEXT = json.load(open(f"{HERE}/report_v5_text.json")) if os.path.exists(f"{HERE}/report_v5_text.json") else {}


def J(p, d=None):
    try: return json.load(open(p))
    except Exception: return d


def img(fn, cap):
    p = f"{FIG}/{fn}"
    if not os.path.exists(p): return f'<p class="note warn">缺图：{escape(fn)}</p>'
    mime = "image/jpeg" if fn.endswith(".jpg") else "image/png"
    return f'<figure><img alt="{escape(cap)}" src="data:{mime};base64,{base64.b64encode(open(p, "rb").read()).decode()}"><figcaption>{escape(cap)}</figcaption></figure>'


def tr(cells, th=False):
    t = "th" if th else "td"; return "<tr>" + "".join(f"<{t}{' class=n' if i else ''}>{c}</{t}>" for i, c in enumerate(cells)) + "</tr>"


def table(head, rows): return "<div class=tw><table>" + tr(head, True) + "".join(tr(r) for r in rows) + "</table></div>"


def f(x, d=3): return "—" if x is None or (isinstance(x, float) and not np.isfinite(x)) else f"{x:.{d}f}"


def ci(p, d=3):
    if not p: return "—"
    cls = "good" if p["lo"] > 0 else ("bad" if p["hi"] < 0 else "")
    return f'<span class="{cls}">{p["mean"]:+.{d}f}</span> <span class=ci>[{p["lo"]:+.{d}f}, {p["hi"]:+.{d}f}]</span>'


def para(key): return "".join(f"<p>{x}</p>" for x in TEXT.get(key, []))


def bullets(key): return "<ul>" + "".join(f"<li>{x}</li>" for x in TEXT.get(key, [])) + "</ul>" if TEXT.get(key) else ""


def ablation_tables(A, order):
    T = A["table"]; rows = []
    for k in order:
        if k not in T: continue
        v = T[k]; rows.append([escape(k), v["n"], f(v["cov_final"][0]), f(v["cov@1000a"][0]), f(v["auc_0_100m"][0]), f(v["stalled"][0], 2), f"{f(v['coll_real'][0], 1)} / {f(v.get('coll_real_median'), 0)}", f(v["fence"][0], 1),
                               f"{f(v['drift_m'][0], 2)} / {f(v.get('drift_m_median'), 2)}", f(v.get("yaw_err_median"), 1), f(v["views_ge3"][0]), f(v["dist_m"][0], 0), f(v["turn_frac"][0], 2), f(v["plan_ms"][0], 0)])
    return table(["配置", "运行", "最终覆盖率", "1000 动作覆盖率", "覆盖–距离 AUC", "停滞率", "碰撞 均值/中位", "围栏阻挡", "位置误差 m 均值/中位", "朝向误差 ° 中位", "≥3 方向体素", "飞行 m", "转向占比", "规划 ms"], rows)


def paired_table(A, pairs):
    rows = []
    for name, key in pairs:
        p = A["paired"].get(key)
        if not p: continue
        rows.append([escape(name), p["cov_final"]["n"] if p["cov_final"] else "—", ci(p["cov_final"]), ci(p["auc_0_100m"]), ci(p["stalled"], 2), ci(p["coll_real"], 1), ci(p["drift_m"], 2), ci(p["views_ge3"])])
    return table(["对比（前者减后者）", "配对数", "最终覆盖率", "AUC", "停滞率", "碰撞", "位置误差 m", "≥3 方向体素"], rows)


